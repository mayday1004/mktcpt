const T2S = new Map(T2S_PAIRS);

// 把字串轉成「搜尋正規型」：
// 1. 全部 lowercase
// 2. 繁體常見字 → 簡體（單向）
// 3. trim 兩端空白
//
// 兩邊都呼叫一次 normalize 後再比對，繁簡查繁簡都能對到。
export function normalizeForSearch(s) {
  if (s == null) return "";
  let r = String(s).toLowerCase().trim();
  let out = "";
  for (const ch of r) out += T2S.get(ch) || ch;
  return out;
}

// 在 ad（含 ad_code/ad_name/group）中比對 query 是否能命中代碼或名稱
export function adMatchesQuery(ad, normalizedQuery) {
  if (!normalizedQuery) return true;
  const code = normalizeForSearch(ad.ad_code);
  const name = normalizeForSearch(ad.ad_name);
  return code.includes(normalizedQuery) || name.includes(normalizedQuery);
}
